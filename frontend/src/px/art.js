// Merge horizontal runs into rects: [{x, y, w, color}]
export function iconRects(grid, tint = null) {
  const out = []
  grid.forEach((row, y) => {
    let x = 0
    while (x < row.length) {
      const ch = row[x]
      if (ch === ".") { x++; continue }
      let w = 1
      while (x + w < row.length && row[x + w] === ch) w++
      out.push({ x, y, w, color: ch === "X" ? tint : PAL[ch] })
      x += w
    }
  })
  return out
}
